import argparse
import re

import joblib
import numpy as np
import pandas as pd
from sklearn.ensemble import RandomForestClassifier
from sklearn.feature_extraction.text import TfidfVectorizer
from sklearn.metrics import accuracy_score, classification_report, confusion_matrix

from split_utils import group_cv_indices, original_case, save_validator_figures

# ==========================================================
# CONFIGURATION
# ==========================================================
DEFAULT_INPUT = './data_bases/04_final/train_validator_final.csv'  # generated by script 08
DEFAULT_MODEL_DIR = './trained_models/'                            # script 16 loads from here
DEFAULT_FIGURES_DIR = './figuras/'
N_FOLDS = 5


def clean_java_code(code):
    if not isinstance(code, str):
        return ""
    code = re.sub(r'//.*', '', code)
    code = re.sub(r'/\*.*?\*/', '', code, flags=re.DOTALL)
    code = re.sub(r'\s+', ' ', code)
    return code.strip().lower()


def pick(df, *names):
    """Returns the first column name that exists (supports the PT and EN versions of the data)."""
    for name in names:
        if name in df.columns:
            return name
    raise ValueError(f"None of the columns {names} found. Available: {list(df.columns)}")


def new_vectorizer():
    return TfidfVectorizer(max_features=1500)


def new_model():
    return RandomForestClassifier(n_estimators=100, random_state=42)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--input', default=DEFAULT_INPUT)
    parser.add_argument('--model-dir', default=DEFAULT_MODEL_DIR)
    parser.add_argument('--figures-dir', default=DEFAULT_FIGURES_DIR)
    parser.add_argument('--show', action='store_true', help='also open the figures on screen')
    args = parser.parse_args()

    print("Starting the Validator Training (The Judge) - Lexical / TF-IDF\n")

    # 1. LOAD DATA
    print("1. Loading the training dataset...")
    df = pd.read_csv(args.input, sep=';')
    id_col = pick(df, 'Case_ID', 'ID_Caso')
    code_col = pick(df, 'Code_Snippet', 'Codigo_Snippet')
    label_col = pick(df, 'Has_Resource_Leak', 'Has_Resource_Leak')
    print(f"   -> Total examples loaded for training: {len(df)}")

    # 2. DATA CLEANING
    print("\n2. Performing Code Cleaning...")
    X_text = df[code_col].apply(clean_java_code).values
    y = df[label_col].values
    groups = df[id_col].apply(original_case).values
    print(f"   -> Original cases (groups): {len(set(groups))}")

    # 3. INTERNAL EVALUATION - cross-validation BY ORIGINAL CASE
    # The vectorizer is fitted only on the training folds, so the test fold stays unseen.
    print(f"\n3. Internal evaluation: {N_FOLDS}-fold cross-validation by original case...")
    oof_pred = np.zeros(len(df), dtype=int)
    fold_acc = []
    for k, (train_idx, test_idx) in enumerate(group_cv_indices(groups, N_FOLDS), 1):
        vectorizer = new_vectorizer()
        X_train = vectorizer.fit_transform(X_text[train_idx])
        X_test = vectorizer.transform(X_text[test_idx])
        model = new_model().fit(X_train, y[train_idx])
        pred = model.predict(X_test)
        oof_pred[test_idx] = pred
        fold_acc.append(accuracy_score(y[test_idx], pred))
        print(f"   fold {k}: {len(set(groups[test_idx]))} cases, "
              f"{len(test_idx)} examples, accuracy {fold_acc[-1] * 100:.2f}%")

    print("\n" + "=" * 50)
    print("VALIDATOR INTERNAL PERFORMANCE (TF-IDF, split by original case)")
    print("=" * 50)
    print(f"Accuracy per fold: mean {np.mean(fold_acc) * 100:.2f}% (std {np.std(fold_acc) * 100:.2f} pp)")
    print(f"Pooled accuracy (all test folds together): {accuracy_score(y, oof_pred) * 100:.2f}%\n")
    print(classification_report(y, oof_pred, target_names=["Correct Code (0)", "With Bug (1)"]))
    matrix = confusion_matrix(y, oof_pred)
    print("Confusion Matrix (pooled over the test folds):")
    print(matrix)
    print("=" * 50)

    # 4. FINAL MODEL: retrain on 100% of the training data (as described in the methodology)
    print("\n4. Retraining on 100% of the training data and saving...")
    vectorizer = new_vectorizer()
    X_all = vectorizer.fit_transform(X_text)
    model = new_model().fit(X_all, y)
    os.makedirs(args.model_dir, exist_ok=True)
    joblib.dump(model, os.path.join(args.model_dir, 'resource_leak_validator.pkl'))
    joblib.dump(vectorizer, os.path.join(args.model_dir, 'vectorizer.pkl'))
    print("Success! '.pkl' files have been created.")

    # 5. FIGURES (saved as PNG, same file names used in the LaTeX)
    save_validator_figures(
        y, oof_pred, args.figures_dir,
        metrics_file='Figura_Y_Metricas_Desempenho.png',
        matrix_file='Figura_Z_Matriz_Confusao.png',
        colors=('#4C72B0', '#DD8452'), cmap='Blues',
        metrics_title='Métricas de Avaliação: Classificador Random Forest (TF-IDF)',
        matrix_title='Matriz de Confusão: Validador de Resource Leaks (TF-IDF)',
        show=args.show)


if __name__ == "__main__":
    main()