import argparse

import joblib
import numpy as np
import pandas as pd
from sklearn.ensemble import RandomForestClassifier
from sklearn.feature_extraction.text import TfidfVectorizer
from sklearn.metrics import accuracy_score, classification_report, confusion_matrix

from split_utils import group_cv_indices, original_case, save_validator_figures

# ==========================================================
# CONFIGURATION
# ==========================================================
DEFAULT_INPUT = 'C:/Dissertacao/data_bases/04_final/dataset_ast_train.csv'  # generated by script 09
DEFAULT_MODEL_DIR = 'C:/Dissertacao/trained_models/'                        # script 17 loads from here
DEFAULT_FIGURES_DIR = './figuras/'
N_FOLDS = 5


def pick(df, *names):
    """Returns the first column name that exists (supports the PT and EN versions of the data)."""
    for name in names:
        if name in df.columns:
            return name
    raise ValueError(f"None of the columns {names} found. Available: {list(df.columns)}")


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--input', default=DEFAULT_INPUT)
    parser.add_argument('--model-dir', default=DEFAULT_MODEL_DIR)
    parser.add_argument('--figures-dir', default=DEFAULT_FIGURES_DIR)
    parser.add_argument('--show', action='store_true', help='also open the figures on screen')
    args = parser.parse_args()

    print("Starting Structural Validator (AST) Training...\n")

    # 1. LOAD DATA
    print(f"1. Loading the training dataset: {args.input}...")
    try:
        df = pd.read_csv(args.input)
    except FileNotFoundError:
        print(f"ERROR: File not found at {args.input}")
        return

    id_col = pick(df, 'Case_ID', 'ID_Caso')
    label_col = pick(df, 'Has_Resource_Leak', 'Has_Resource_Leak')
    print(f"   -> Total examples loaded: {len(df)}")

    # Handle possible null values in case some code did not extract features
    df['AST_Features'] = df['AST_Features'].fillna("NO_FEATURES")

    X_text = df['AST_Features'].values
    y = df[label_col].values
    groups = df[id_col].apply(original_case).values
    print(f"   -> Original cases (groups): {len(set(groups))}")

    # 2. INTERNAL EVALUATION - cross-validation BY ORIGINAL CASE
    # The vectorizer is fitted only on the training folds, so the test fold stays unseen.
    print(f"\n2. Internal evaluation: {N_FOLDS}-fold cross-validation by original case...")
    oof_pred = np.zeros(len(df), dtype=int)
    fold_acc = []
    for k, (train_idx, test_idx) in enumerate(group_cv_indices(groups, N_FOLDS), 1):
        vectorizer = TfidfVectorizer()
        X_train = vectorizer.fit_transform(X_text[train_idx])
        X_test = vectorizer.transform(X_text[test_idx])
        model = RandomForestClassifier(n_estimators=100, random_state=42).fit(X_train, y[train_idx])
        pred = model.predict(X_test)
        oof_pred[test_idx] = pred
        fold_acc.append(accuracy_score(y[test_idx], pred))
        print(f"   fold {k}: {len(set(groups[test_idx]))} cases, "
              f"{len(test_idx)} examples, accuracy {fold_acc[-1] * 100:.2f}%")

    print("\n" + "=" * 50)
    print("INTERNAL PERFORMANCE OF AST VALIDATOR (split by original case)")
    print("=" * 50)
    print(f"Accuracy per fold: mean {np.mean(fold_acc) * 100:.2f}% (std {np.std(fold_acc) * 100:.2f} pp)")
    print(f"Pooled accuracy (all test folds together): {accuracy_score(y, oof_pred) * 100:.2f}%\n")
    print(classification_report(y, oof_pred, target_names=["Fixed (0)", "With Bug (1)"]))
    matrix = confusion_matrix(y, oof_pred)
    print("Confusion Matrix (pooled over the test folds):")
    print(matrix)
    print("=" * 50)

    # 3. FINAL MODEL: retrain on 100% of the training data (as described in the methodology)
    print("\n3. Retraining on 100% of the training data and saving the AST oracle...")
    vectorizer = TfidfVectorizer()
    X_all = vectorizer.fit_transform(X_text)
    model = RandomForestClassifier(n_estimators=100, random_state=42).fit(X_all, y)

    vocabulary = sorted(vectorizer.vocabulary_)
    print(f"   -> Structural vocabulary ({len(vocabulary)} tokens): {vocabulary}")
    if 'hasresources_implicitclose' not in vocabulary:
        print("   -> NOTE: 'HasResources_ImplicitClose' (try-with-resources) is NOT in the vocabulary: "
              "the training data has no try-with-resources, so this validator cannot see that pattern.")

    os.makedirs(args.model_dir, exist_ok=True)
    joblib.dump(model, os.path.join(args.model_dir, 'validador_ast_rf.pkl'))
    joblib.dump(vectorizer, os.path.join(args.model_dir, 'vectorizer_ast.pkl'))
    print("Success! Files 'validador_ast_rf.pkl' and 'vectorizer_ast.pkl' were created.")

    # 4. FIGURES (saved as PNG)
    save_validator_figures(
        y, oof_pred, args.figures_dir,
        metrics_file='Figura_AST_Metricas_Desempenho.png',
        matrix_file='Figura_AST_Matriz_Confusao.png',
        colors=('#2ca02c', '#d62728'), cmap='Greens',
        metrics_title='Desempenho do Validador Estrutural (AST)',
        matrix_title='Matriz de Confusão - Modelo AST',
        show=args.show)


if __name__ == "__main__":
    main()